/**
 * 从题库中随机抽取指定数量的问题
 */
export function getRandomBehavioralQuestions(count: number = 1): BehavioralQuestion[] {
  const shuffled = [...BEHAVIORAL_QUESTIONS].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

/**
 * 获取所有类别列表
 */
export function getBehavioralCategories(): string[] {
  const categories = new Set(BEHAVIORAL_QUESTIONS.map((q) => q.category));
  return Array.from(categories);
}

/**
 * 根据类别获取问题
 */
export function getQuestionsByCategory(category: string): BehavioralQuestion[] {
  return BEHAVIORAL_QUESTIONS.filter((q) => q.category === category);
}
